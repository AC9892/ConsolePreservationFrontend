use crate::machine::{hash_file, read_json, Result, Workspace};
use serde::Serialize;
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::path::Path;

#[derive(Debug, Serialize)]
pub struct VerificationCheck {
    pub label: String,
    pub source: String,
    pub expected: String,
    pub actual: String,
    pub matches: bool,
}

#[derive(Debug, Serialize)]
pub struct VerificationReport {
    pub checks: Vec<VerificationCheck>,
    pub all_verified: bool,
    pub nand_association: String,
}

fn string<'a>(value: &'a Value, key: &str) -> Result<&'a str> {
    value
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("Missing {key} in preservation record"))
}

fn add_file(
    checks: &mut Vec<VerificationCheck>,
    label: &str,
    source: &str,
    path: &Path,
    expected: &str,
) {
    let actual = hash_file(path).unwrap_or_else(|error| format!("Unavailable: {error}"));
    checks.push(VerificationCheck {
        label: label.into(),
        source: source.into(),
        expected: expected.into(),
        matches: actual.eq_ignore_ascii_case(expected),
        actual,
    });
}

fn canonical_hash(value: &Value) -> Result<String> {
    let mut unsigned = value.clone();
    unsigned
        .as_object_mut()
        .ok_or("Capture record is not a JSON object")?
        .remove("capture_hash");
    let bytes = serde_json::to_vec(&unsigned).map_err(|e| e.to_string())?;
    Ok(format!("sha256:{}", hex::encode(Sha256::digest(bytes))))
}

fn add_capture_hash(
    checks: &mut Vec<VerificationCheck>,
    label: &str,
    source: &str,
    value: &Value,
) -> Result<()> {
    let expected = string(value, "capture_hash")?.to_owned();
    let actual = canonical_hash(value)?;
    checks.push(VerificationCheck {
        label: label.into(),
        source: source.into(),
        matches: actual == expected,
        expected,
        actual,
    });
    Ok(())
}

impl Workspace {
    pub fn verify_preservation(&self, id: &str) -> Result<VerificationReport> {
        let machine = self.machine_dir(id)?;
        let profile = read_json(&machine.join("machine.json"))?;
        let nand = read_json(&machine.join("nand/source.json"))?;
        let capture_id = string(&profile, "capture_id")?;
        if capture_id.is_empty()
            || !capture_id
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-')
        {
            return Err("Invalid capture ID".into());
        }
        let capture_dir = machine.join("captures").join(capture_id);
        let manifest = read_json(&capture_dir.join("manifest.json"))?;
        let mut checks = Vec::new();

        add_file(
            &mut checks,
            "NAND source",
            "NAND Backup – Association Unverified",
            Path::new(string(&nand, "path")?),
            string(&nand, "calculated_sha256")?,
        );
        add_file(
            &mut checks,
            "Virtual NAND",
            "Generated by CPF",
            &machine.join("nand/virtual_nand.bin"),
            string(&profile, "virtual_nand_sha256")?,
        );
        add_capture_hash(
            &mut checks,
            "Capture manifest",
            "Live Agent Capture and SD Metadata Capture",
            &manifest,
        )?;

        for (key, label, provenance) in [
            (
                "system_observation",
                "Agent system observation",
                "Live Agent Capture",
            ),
            (
                "sd_inventory",
                "SD directory inventory",
                "SD Metadata Capture",
            ),
            (
                "last_recorded_cpf_boot",
                "Agent boot manifest",
                "Live Agent Capture",
            ),
            (
                "unlinked_nand_backup",
                "NAND title capture",
                "NAND Backup – Association Unverified",
            ),
        ] {
            let Some(record) = manifest.get(key) else {
                continue;
            };
            let source = record
                .get("source")
                .ok_or_else(|| format!("Missing source for {key}"))?;
            let relative = string(source, "bundle_file")?;
            let relative_path = Path::new(relative);
            if relative_path.is_absolute()
                || relative_path
                    .components()
                    .any(|part| !matches!(part, std::path::Component::Normal(_)))
            {
                return Err(format!("Invalid bundled capture path: {relative}"));
            }
            let path = capture_dir.join(relative_path);
            add_file(
                &mut checks,
                label,
                provenance,
                &path,
                string(source, "bundle_sha256")?,
            );
            if source.get("source_capture_hash").is_some() && path.is_file() {
                let value = read_json(&path)?;
                add_capture_hash(&mut checks, &format!("{label} record"), provenance, &value)?;
            }
        }
        Ok(VerificationReport {
            all_verified: checks.iter().all(|check| check.matches),
            checks,
            nand_association: string(&profile, "nand_association")?.into(),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn capture_hash_uses_sorted_compact_json() {
        let value = json!({"z": 1, "a": {"b": true}});
        let expected = format!(
            "sha256:{}",
            hex::encode(Sha256::digest(b"{\"a\":{\"b\":true},\"z\":1}"))
        );
        assert_eq!(canonical_hash(&value).unwrap(), expected);
    }
}
