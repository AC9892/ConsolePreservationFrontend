use cpf_core::{hash_file, read_json, Workspace};
use serde_json::{json, Value};
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};
use time::OffsetDateTime;

fn now() -> String {
    OffsetDateTime::now_utc()
        .format(&time::format_description::well_known::Rfc3339)
        .unwrap_or_default()
}
fn token() -> String {
    format!(
        "{}-{}",
        std::process::id(),
        OffsetDateTime::now_utc().unix_timestamp_nanos()
    )
}
fn write_json(path: &Path, value: &Value) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    fs::write(
        path,
        serde_json::to_vec_pretty(value).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())
}
fn event(path: &Path, value: Value) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let mut file = OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
        .map_err(|e| e.to_string())?;
    writeln!(file, "{}", value).map_err(|e| e.to_string())
}
fn copy_verified(source: &Path, target: &Path, digest: &str) -> Result<(), String> {
    if let Some(parent) = target.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    fs::copy(source, target).map_err(|e| e.to_string())?;
    if hash_file(target)? != digest {
        return Err(format!("Copy verification failed: {}", target.display()));
    }
    Ok(())
}
fn relative(machine: &Path, path: &Path) -> String {
    path.strip_prefix(machine)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}
fn host_files(root: &Path) -> Result<(std::collections::HashMap<String, u64>, usize), String> {
    let mut files = std::collections::HashMap::new();
    let mut count = 0;
    let mut pending = vec![root.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for item in fs::read_dir(&dir).map_err(|e| e.to_string())? {
            let item = item.map_err(|e| e.to_string())?;
            let path = item.path();
            let meta = fs::symlink_metadata(&path).map_err(|e| e.to_string())?;
            if meta.file_type().is_symlink() {
                return Err(format!("Linked SD path is unsupported: {}", path.display()));
            }
            count += 1;
            if meta.is_dir() {
                pending.push(path)
            } else if meta.is_file() {
                files.insert(relative(root, &path), meta.len());
            }
        }
    }
    Ok((files, count))
}
fn indexed_files(path: &Path) -> std::collections::HashMap<String, u64> {
    let mut files = std::collections::HashMap::new();
    let Ok(content) = fs::read_to_string(path) else {
        return files;
    };
    for line in content.lines() {
        let parts: Vec<&str> = line.splitn(6, ' ').collect();
        if parts.len() == 6 && parts[0] == "FILE" {
            if let Ok(size) = parts[2].parse() {
                files.insert(parts[5].replace('\\', "/"), size);
            }
        }
    }
    files
}

struct AuditFile {
    target: PathBuf,
    before: String,
    snapshot: PathBuf,
    manifest: PathBuf,
    reason: &'static str,
}
impl AuditFile {
    fn new(
        machine: &Path,
        target: PathBuf,
        category: &str,
        manifest: PathBuf,
        reason: &'static str,
    ) -> Result<Self, String> {
        let before = hash_file(&target)?;
        let snapshot = machine
            .join("snapshots")
            .join(category)
            .join(format!("before-runtime-{}.bin", token()));
        copy_verified(&target, &snapshot, &before)?;
        Ok(Self {
            target,
            before,
            snapshot,
            manifest,
            reason,
        })
    }
    fn finish(self, machine: &Path) -> Result<(String, bool), String> {
        let after = hash_file(&self.target)?;
        let changed = after != self.before;
        if changed {
            event(
                &self.manifest,
                json!({"modification_id":token(),"target":relative(machine,&self.target),"original_hash":self.before,"modified_hash":after,"reason":self.reason,"tool_version":"CPF Rust libretro worker 0.1","timestamp":now(),"reversible":true,"reversal_snapshot":relative(machine,&self.snapshot),"source":"Generated by CPF"}),
            )?;
        } else {
            fs::remove_file(&self.snapshot).map_err(|e| e.to_string())?;
        }
        Ok((after, changed))
    }
}

pub struct Session {
    pub machine: PathBuf,
    pub system: PathBuf,
    pub save: PathBuf,
    pub sd_enabled: bool,
    lock: PathBuf,
    nand: Option<AuditFile>,
    firmware: Option<AuditFile>,
    sd_before: Option<(String, PathBuf)>,
}
impl Session {
    pub fn prepare(workspace: &Workspace, id: &str) -> Result<Self, String> {
        let machine = workspace.machine_dir(id)?;
        if workspace
            .runtime_status(id)?
            .get("running")
            .and_then(Value::as_bool)
            == Some(true)
        {
            return Err("Another console session is running".into());
        }
        let ready = workspace.readiness(id)?;
        if !ready.ready_to_attempt_boot {
            return Err(format!(
                "Missing runtime files: {}",
                ready.missing.join(", ")
            ));
        }
        let work = machine.join("runtime/libretro");
        let system = work.join("system");
        let core_system = system.join("melonDS DS");
        let save = work.join("save");
        fs::create_dir_all(&core_system).map_err(|e| e.to_string())?;
        fs::create_dir_all(&save).map_err(|e| e.to_string())?;
        let lock = work.join("running.json");
        if lock.exists() {
            return Err("Another console session holds the runtime lock".into());
        }
        let mut lockfile = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&lock)
            .map_err(|e| e.to_string())?;
        writeln!(
            lockfile,
            "{}",
            json!({"pid":std::process::id(),"started":now(),"state":"booting"})
        )
        .map_err(|e| e.to_string())?;
        let result = (|| {
            let prior = read_json(&work.join("boot_sources.json")).unwrap_or(Value::Null);
            let mut imported = serde_json::Map::new();
            for (name, source) in workspace.boot_files(id)? {
                let source = source.ok_or(format!("Missing {name}"))?;
                let digest = hash_file(&source)?;
                let destination = core_system.join(&name);
                if name == "dsi_firmware.bin" {
                    let meta = read_json(&work.join("firmware_base.json")).unwrap_or(Value::Null);
                    let adopted = prior
                        .get(&name)
                        .and_then(|v| v.get("sha256"))
                        .and_then(Value::as_str)
                        == Some(&digest);
                    let base = meta.get("base_sha256").and_then(Value::as_str) == Some(&digest)
                        || (meta.is_null() && adopted);
                    if destination.is_symlink() {
                        return Err("Working firmware cannot be a link".into());
                    }
                    if !destination.is_file() || !base {
                        if destination.is_file() {
                            let old = hash_file(&destination)?;
                            let snapshot = machine
                                .join(format!("snapshots/firmware/before-rebase-{}.bin", token()));
                            copy_verified(&destination, &snapshot, &old)?;
                            event(
                                &machine.join("logs/events.jsonl"),
                                json!({"timestamp":now(),"kind":"RUNTIME_FIRMWARE_SNAPSHOT","source":"Generated by CPF","path":relative(&machine,&snapshot),"sha256":old}),
                            )?;
                        }
                        copy_verified(&source, &destination, &digest)?;
                    }
                    write_json(
                        &work.join("firmware_base.json"),
                        &json!({"base_sha256":digest,"source":"User-owned boot file"}),
                    )?;
                } else if !destination.is_file() || hash_file(&destination)? != digest {
                    copy_verified(&source, &destination, &digest)?;
                }
                imported.insert(name, json!({"source":source,"sha256":digest}));
            }
            write_json(&work.join("boot_sources.json"), &Value::Object(imported))?;
            // Imported firmware is protected at rest, but the emulated DSi must
            // be able to persist settings in its separate runtime copy.
            let working_firmware = core_system.join("dsi_firmware.bin");
            let mut permissions = fs::metadata(&working_firmware).map_err(|e| e.to_string())?.permissions();
            permissions.set_readonly(false);
            fs::set_permissions(&working_firmware, permissions).map_err(|e| e.to_string())?;
            let firmware = AuditFile::new(
                &machine,
                core_system.join("dsi_firmware.bin"),
                "firmware",
                machine.join("runtime/firmware_modifications.jsonl"),
                "DSi firmware write during emulation",
            )?;
            let profile = read_json(&machine.join("machine.json"))?;
            let virtual_nand = machine.join("nand/virtual_nand.bin");
            let base = hash_file(&virtual_nand)?;
            if profile.get("virtual_nand_sha256").and_then(Value::as_str) != Some(&base) {
                return Err("Virtual NAND hash changed outside CPF".into());
            }
            let nand_target = core_system.join("dsi_nand.bin");
            let meta = read_json(&work.join("nand_base.json")).unwrap_or(Value::Null);
            if !nand_target.is_file()
                || meta.get("base_sha256").and_then(Value::as_str) != Some(&base)
            {
                if nand_target.is_file() {
                    let old = hash_file(&nand_target)?;
                    let snapshot = machine.join(format!("snapshots/nand/libretro-{}.bin", token()));
                    copy_verified(&nand_target, &snapshot, &old)?;
                    event(
                        &machine.join("logs/events.jsonl"),
                        json!({"timestamp":now(),"kind":"RUNTIME_NAND_SNAPSHOT","source":"Generated by CPF","path":relative(&machine,&snapshot),"sha256":old}),
                    )?;
                }
                let staged = core_system.join(format!(".dsi_nand-{}.bin", token()));
                copy_verified(&virtual_nand, &staged, &base)?;
                if nand_target.exists() {
                    fs::remove_file(&nand_target).map_err(|e| e.to_string())?;
                }
                fs::rename(&staged, &nand_target).map_err(|e| e.to_string())?;
                write_json(
                    &work.join("nand_base.json"),
                    &json!({"base_sha256":base,"source":"Generated by CPF"}),
                )?;
            }
            let nand = AuditFile::new(
                &machine,
                nand_target,
                "nand",
                machine.join("nand/modifications.jsonl"),
                "DSi runtime write during emulation",
            )?;
            let config = read_json(&machine.join("runtime/config.json"))?;
            let sd_enabled = config
                .get("virtual_sd_enabled")
                .and_then(Value::as_bool)
                .unwrap_or(false);
            let sd_image = save.join("melonDS DS/dsi_sd_card.bin");
            let sd_before = if sd_enabled && sd_image.is_file() {
                let hash = hash_file(&sd_image)?;
                let snapshot = machine.join(format!(
                    "sd/snapshots/runtime-before-{}/dsi_sd_card.bin",
                    token()
                ));
                copy_verified(&sd_image, &snapshot, &hash)?;
                Some((hash, snapshot))
            } else {
                None
            };
            if sd_enabled {
                fs::create_dir_all(save.join("melonDS DS/dsi_sd_card"))
                    .map_err(|e| e.to_string())?;
            }
            Ok((nand, firmware, sd_enabled, sd_before))
        })();
        match result {
            Ok((nand, firmware, sd_enabled, sd_before)) => Ok(Self {
                machine,
                system,
                save,
                sd_enabled,
                lock,
                nand: Some(nand),
                firmware: Some(firmware),
                sd_before,
            }),
            Err(e) => {
                let _ = fs::remove_file(lock);
                Err(e)
            }
        }
    }
    pub fn running(&self) -> Result<(), String> {
        write_json(
            &self.lock,
            &json!({"pid":std::process::id(),"started":now(),"state":"running"}),
        )?;
        self.status(true, false, 0)?;
        event(
            &self.machine.join("logs/events.jsonl"),
            json!({"timestamp":now(),"kind":"BOOT_REQUESTED","source":"Generated by CPF","backend":"melonDS DS libretro","working_nand":self.system.join("melonDS DS/dsi_nand.bin"),"working_nand_sha256":self.nand.as_ref().map(|a|&a.before),"menu_boot_verified":false}),
        )
    }
    pub fn status(&self, running: bool, paused: bool, frames: u64) -> Result<(), String> {
        write_json(
            &self.machine.join("runtime/libretro/status.json"),
            &json!({"schema":"cpf.dsi.runtime-status/1","backend":"melonDS DS libretro","pid":std::process::id(),"running":running,"paused":paused,"frames":frames,"updated_at":now(),"menu_boot_verified":false}),
        )
    }
    pub fn diagnostic(&self, value: Value) {
        let _ = event(&self.machine.join("logs/diagnostics.jsonl"), value);
    }
    pub fn finish(mut self, frames: u64) -> Result<(), String> {
        let nand_before = self.nand.as_ref().map(|a| a.before.clone());
        let firmware_before = self.firmware.as_ref().map(|a| a.before.clone());
        let nand = self
            .nand
            .take()
            .map(|v| v.finish(&self.machine))
            .transpose()?;
        let firmware = self
            .firmware
            .take()
            .map(|v| v.finish(&self.machine))
            .transpose()?;
        let sd_image = self.save.join("melonDS DS/dsi_sd_card.bin");
        let sd_after = if self.sd_enabled && sd_image.is_file() {
            Some(hash_file(&sd_image)?)
        } else {
            None
        };
        if let Some((before, snapshot)) = self.sd_before.take() {
            if sd_after.as_deref() == Some(&before) {
                let _ = fs::remove_file(snapshot);
            } else {
                event(
                    &self.machine.join("logs/events.jsonl"),
                    json!({"timestamp":now(),"kind":"SD_IMAGE_CHANGED","source":"Generated by CPF","target":sd_image,"original_hash":before,"modified_hash":sd_after,"reversal_snapshot":relative(&self.machine,&snapshot),"reversible":true}),
                )?;
            }
        } else if sd_after.is_some() {
            event(
                &self.machine.join("logs/events.jsonl"),
                json!({"timestamp":now(),"kind":"SD_IMAGE_CREATED","source":"Generated by CPF","target":sd_image,"original_hash":Value::Null,"modified_hash":sd_after,"reversible":false}),
            )?;
        }
        if let Some(ref hash) = sd_after {
            let config_path = self.machine.join("sd/virtual.json");
            let mut config = read_json(&config_path).unwrap_or(json!({}));
            let host = self.save.join("melonDS DS/dsi_sd_card");
            let index = self.save.join("melonDS DS/dsi_sd_card.bin.idx");
            let (host_map, host_count) = if host.is_dir() {
                host_files(&host)?
            } else {
                (Default::default(), 0)
            };
            let indexed = indexed_files(&index);
            let matches = host.is_dir() && host_map == indexed;
            if host.is_dir() && !matches {
                event(
                    &self.machine.join("logs/events.jsonl"),
                    json!({"timestamp":now(),"kind":"SD_HOST_SYNC_MISMATCH","source":"Generated by CPF","host_file_count":host_map.len(),"indexed_file_count":indexed.len()}),
                )?;
            }
            let pending =
                config.get("state").and_then(Value::as_str) == Some("pending_runtime_import");
            let requested = config
                .get("pending_import_files")
                .and_then(Value::as_object);
            let imported = requested
                .map(|entries| {
                    entries
                        .iter()
                        .filter(|(_, v)| v.get("type").and_then(Value::as_str) == Some("file"))
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default();
            let indexed_count = imported
                .iter()
                .filter(|(name, v)| {
                    indexed.get(*name) == v.get("size_bytes").and_then(Value::as_u64).as_ref()
                })
                .count();
            let import_indexed = pending && matches && indexed_count == imported.len();
            if pending {
                event(
                    &self.machine.join("logs/events.jsonl"),
                    json!({"timestamp":now(),"kind":if import_indexed{"SD_IMPORT_INDEXED"}else{"SD_IMPORT_NOT_INDEXED"},"source":"Generated by CPF","expected_files":imported.len(),"indexed_files":indexed_count}),
                )?;
            }
            config["state"] = json!(if pending && !import_indexed {
                "pending_runtime_import"
            } else {
                "runtime_image"
            });
            config["backend_image"] = json!(sd_image);
            config["image_sha256"] = json!(hash);
            let logical = fs::read_to_string(&index).ok().and_then(|s| {
                s.lines()
                    .next()
                    .and_then(|l| l.strip_prefix("SIZE ").and_then(|v| v.parse::<u64>().ok()))
            });
            config["logical_size_bytes"] = json!(logical);
            config["host_sync_path"] = json!(host);
            config["host_sync_active"] = json!(matches && (!pending || import_indexed));
            config["host_entry_count"] = json!(host_count);
            config["actual_file_contents_indexed"] = json!(matches && (!pending || import_indexed));
            if import_indexed {
                config
                    .as_object_mut()
                    .unwrap()
                    .remove("pending_import_files");
            }
            write_json(&config_path, &config)?;
            let profile_path = self.machine.join("machine.json");
            let mut profile = read_json(&profile_path)?;
            profile["virtual_sd_mode"] = json!("runtime_image");
            write_json(&profile_path, &profile)?;
        }
        event(
            &self.machine.join("logs/events.jsonl"),
            json!({"timestamp":now(),"kind":"RUNTIME_STOPPED","source":"Generated by CPF","frames":frames,"working_nand_sha256_before":nand_before,"working_nand_sha256_after":nand.as_ref().map(|a|&a.0),"nand_changed":nand.as_ref().map(|a|a.1),"working_firmware_sha256_before":firmware_before,"working_firmware_sha256_after":firmware.as_ref().map(|a|&a.0),"firmware_changed":firmware.as_ref().map(|a|a.1),"sd_image_sha256":sd_after}),
        )?;
        self.status(false, false, frames)?;
        fs::remove_file(&self.lock).map_err(|e| e.to_string())?;
        Ok(())
    }
}
impl Drop for Session {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.lock);
    }
}
