//! Bounded history for snapshots generated automatically by the worker.
//! Manual snapshots and original console sources are never candidates.
use serde_json::json;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::time::SystemTime;

const KEEP: usize = 3;

fn regular(path: &Path, directory: bool) -> bool {
    let Ok(meta) = fs::symlink_metadata(path) else { return false };
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        if meta.file_attributes() & 0x400 != 0 { return false; }
    }
    !meta.file_type().is_symlink() && if directory { meta.is_dir() } else { meta.is_file() }
}

fn token(value: &str) -> bool {
    if value.len() == 32 && value.bytes().all(|c| c.is_ascii_hexdigit()) { return true; }
    let Some((pid, timestamp)) = value.split_once('-') else { return false };
    !pid.is_empty() && !timestamp.is_empty()
        && pid.bytes().all(|c| c.is_ascii_digit())
        && timestamp.bytes().all(|c| c.is_ascii_digit())
}

fn automatic(name: &str, prefixes: &[&str], suffix: &str) -> bool {
    prefixes.iter().any(|prefix| name.strip_prefix(prefix)
        .and_then(|s| s.strip_suffix(suffix)).is_some_and(token))
}

fn candidates(machine: &Path, group: &str) -> Result<Vec<PathBuf>, String> {
    let (parent, prefixes, sd): (PathBuf, &[&str], bool) = match group {
        "nand" => (machine.join("snapshots/nand"), &["before-runtime-", "libretro-"], false),
        "firmware" => (machine.join("snapshots/firmware"), &["before-runtime-", "before-rebase-"], false),
        "sd" => (machine.join("sd/snapshots"), &["runtime-before-"], true),
        _ => return Err("Unknown snapshot group".into()),
    };
    // Check every directory component; do not traverse links or junctions.
    let mut checked = machine.to_path_buf();
    if !regular(&checked, true) { return Err("Machine directory is not a regular directory".into()); }
    for part in parent.strip_prefix(machine).map_err(|e| e.to_string())?.components() {
        checked.push(part);
        if !checked.exists() { return Ok(Vec::new()); }
        if !regular(&checked, true) { return Err("Linked snapshot directories are unsupported".into()); }
    }
    let mut out = Vec::new();
    for item in fs::read_dir(&parent).map_err(|e| e.to_string())? {
        let item = item.map_err(|e| e.to_string())?;
        let name = item.file_name().to_string_lossy().into_owned();
        if !automatic(&name, prefixes, if sd { "" } else { ".bin" }) { continue; }
        let path = item.path();
        if sd {
            if !regular(&path, true) { continue; }
            let image = path.join("dsi_sd_card.bin");
            // Never remove a directory containing extra user files.
            if regular(&image, false) && fs::read_dir(&path).map_err(|e| e.to_string())?.count() == 1 {
                out.push(image);
            }
        } else if regular(&path, false) { out.push(path); }
    }
    Ok(out)
}

pub fn prune(machine: &Path) -> Result<(), String> {
    for group in ["nand", "firmware", "sd"] {
        let mut files = candidates(machine, group)?;
        files.sort_by_key(|p| (fs::metadata(p).and_then(|m| m.modified()).unwrap_or(SystemTime::UNIX_EPOCH), p.clone()));
        let remove_count = files.len().saturating_sub(KEEP);
        for path in files.into_iter().take(remove_count) {
            let relative = path.strip_prefix(machine).map_err(|e| e.to_string())?.to_string_lossy().replace('\\', "/");
            let bytes = fs::metadata(&path).map_err(|e| e.to_string())?.len();
            let mut log = OpenOptions::new().create(true).append(true).open(machine.join("logs/events.jsonl")).map_err(|e| e.to_string())?;
            // Record intent before removal, then a completion record. Historic
            // modification hashes remain intact; the completion retires rollback.
            writeln!(log, "{}", json!({"kind":"SNAPSHOT_PRUNE_REQUESTED","snapshot":relative,"category":group,"keep":KEEP,"bytes":bytes})).map_err(|e| e.to_string())?;
            log.sync_all().map_err(|e| e.to_string())?;
            fs::remove_file(&path).map_err(|e| e.to_string())?;
            writeln!(log, "{}", json!({"kind":"SNAPSHOT_PRUNED","timestamp":time::OffsetDateTime::now_utc().format(&time::format_description::well_known::Rfc3339).unwrap_or_default(),"source":"Generated by CPF","snapshot":relative,"category":group,"bytes":bytes,"reason":"Automatic snapshot retention","reversal_snapshot_available":false})).map_err(|e| e.to_string())?;
            if group == "sd" { let _ = fs::remove_dir(path.parent().ok_or("Missing snapshot directory")?); }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keeps_newest_three_and_preserves_manual_and_current_files() {
        let root = std::env::temp_dir().join(format!("cpf-retention-{}-{}", std::process::id(), SystemTime::now().duration_since(SystemTime::UNIX_EPOCH).unwrap().as_nanos()));
        for dir in ["snapshots/nand", "snapshots/firmware", "sd/snapshots", "logs", "nand"] { fs::create_dir_all(root.join(dir)).unwrap(); }
        for group in ["nand", "firmware"] {
            for n in 1..=5 {
                let path = root.join(format!("snapshots/{group}/before-runtime-1-{n}.bin"));
                fs::write(&path, [n]).unwrap();
                OpenOptions::new().write(true).open(path).unwrap().set_times(fs::FileTimes::new().set_modified(SystemTime::UNIX_EPOCH + std::time::Duration::from_secs(n as u64))).unwrap();
            }
            fs::write(root.join(format!("snapshots/{group}/manual.bin")), b"manual").unwrap();
        }
        for n in 1..=5 {
            let dir = root.join(format!("sd/snapshots/runtime-before-1-{n}"));
            fs::create_dir(&dir).unwrap(); fs::write(dir.join("dsi_sd_card.bin"), [n]).unwrap();
        }
        let manual = root.join("sd/snapshots/runtime-before-1-0");
        fs::create_dir(&manual).unwrap(); fs::write(manual.join("dsi_sd_card.bin"), b"sd").unwrap(); fs::write(manual.join("notes.txt"), b"keep").unwrap();
        fs::write(root.join("nand/virtual_nand.bin"), b"current").unwrap();
        prune(&root).unwrap();
        for group in ["nand", "firmware", "sd"] { assert_eq!(candidates(&root, group).unwrap().len(), KEEP); }
        for group in ["nand", "firmware"] {
            for n in 1..=5 { assert_eq!(root.join(format!("snapshots/{group}/before-runtime-1-{n}.bin")).exists(), n >= 3); }
        }
        assert!(root.join("snapshots/nand/manual.bin").exists());
        assert!(root.join("snapshots/firmware/manual.bin").exists());
        assert!(manual.join("dsi_sd_card.bin").exists());
        assert_eq!(fs::read(root.join("nand/virtual_nand.bin")).unwrap(), b"current");
        assert_eq!(fs::read_to_string(root.join("logs/events.jsonl")).unwrap().matches("\"kind\":\"SNAPSHOT_PRUNED\"").count(), 6);
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn only_recognizes_generated_names() {
        assert!(automatic("before-runtime-123-456.bin", &["before-runtime-"], ".bin"));
        assert!(!automatic("before-runtime-my-backup.bin", &["before-runtime-"], ".bin"));
        assert!(!automatic("manual.bin", &["before-runtime-"], ".bin"));
    }
}
