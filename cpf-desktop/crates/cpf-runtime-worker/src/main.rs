mod libretro;
mod preservation;

use base64::{engine::general_purpose::STANDARD, Engine};
use cpf_core::{hash_file, inspect_nds, read_json, Workspace};
use libretro::Core;
use preservation::Session;
use serde_json::{json, Value};
use std::io::{self, BufRead, Write};
use std::path::Path;
use std::sync::mpsc;
use std::time::{Duration, Instant};

fn send(value: Value) {
    let mut out = io::stdout().lock();
    let _ = writeln!(out, "{value}");
    let _ = out.flush();
}
fn stage(name: &str) {
    send(json!({"kind":"progress","stage":name}));
}

fn write_slot(machine: &Path, value: &Value) -> Result<(), String> {
    let path = machine.join("runtime/cartridge.json");
    std::fs::write(&path, serde_json::to_vec_pretty(value).map_err(|e| e.to_string())?)
        .map_err(|e| format!("Could not update Slot-1 record: {e}"))
}

fn record_cartridge_event(machine: &Path, kind: &str, slot: &Value) {
    let path = machine.join("logs/events.jsonl");
    let timestamp = time::OffsetDateTime::now_utc()
        .format(&time::format_description::well_known::Rfc3339).unwrap_or_default();
    let event = json!({"kind":kind,"timestamp":timestamp,"source":"Generated by CPF",
        "runtime_inserted":true,"sha256":slot.pointer("/metadata/sha256")});
    if let Ok(mut file) = std::fs::OpenOptions::new().create(true).append(true).open(path) {
        let _ = writeln!(file, "{event}");
    }
}

fn save_current_cartridge(core: &Core, machine: &Path, slot: &Value) -> Result<(), String> {
    let Some(hash) = slot.pointer("/metadata/sha256").and_then(Value::as_str) else { return Ok(()); };
    let Some(bytes) = core.copy_cart_save()? else { return Ok(()); };
    let directory = machine.join("saves/cartridge");
    std::fs::create_dir_all(&directory).map_err(|e| e.to_string())?;
    let save = directory.join(format!("{hash}.sav"));
    let staged = directory.join(format!("{hash}.sav.tmp"));
    std::fs::write(&staged, bytes).map_err(|e| e.to_string())?;
    std::fs::rename(&staged, &save).map_err(|e| format!("Could not preserve cartridge save: {e}"))
}

fn live_insert(core: &Core, machine: &Path, source: &Path) -> Result<Value, String> {
    if !core.live_cart_supported() { return Err("This melonDS core has no live Slot-1 adapter".into()); }
    if core.cart_inserted() != Some(false) { return Err("Eject the current cartridge first".into()); }
    let info = inspect_nds(source)?;
    if info.size_bytes > 512 * 1024 * 1024 { return Err("Cartridge image is too large for live insertion".into()); }
    let directory = machine.join("runtime/cartridges");
    std::fs::create_dir_all(&directory).map_err(|e| e.to_string())?;
    let image = directory.join(format!("{}.nds", info.sha256));
    if !image.exists() { std::fs::copy(source, &image).map_err(|e| e.to_string())?; }
    if hash_file(&image)? != info.sha256 { return Err("Working cartridge copy failed SHA-256 verification".into()); }
    let rom = std::fs::read(&image).map_err(|e| e.to_string())?;
    let save_path = machine.join("saves/cartridge").join(format!("{}.sav", info.sha256));
    let save = if save_path.exists() { Some(std::fs::read(&save_path).map_err(|e| e.to_string())?) } else { None };
    core.insert_cart(&rom, save.as_deref())?;
    if core.cart_inserted() != Some(true) { return Err("melonDS did not confirm the live cartridge".into()); }
    let record = json!({"inserted":true,"image":format!("runtime/cartridges/{}.nds",info.sha256),
        "source_path":source.to_string_lossy(),"source":"User-owned cartridge image",
        "metadata":info,"runtime_inserted":true});
    if let Err(error) = write_slot(machine, &record) { let _ = core.eject_cart(); return Err(error); }
    Ok(record)
}

fn live_eject(core: &Core, machine: &Path, slot: &Value) -> Result<Value, String> {
    if core.cart_inserted() != Some(true) { return Err("Slot-1 is already empty".into()); }
    save_current_cartridge(core, machine, slot)?;
    core.eject_cart()?;
    if core.cart_inserted() != Some(false) { return Err("melonDS still reports a cartridge in Slot-1".into()); }
    let empty = json!({"inserted":false,"image":null});
    write_slot(machine, &empty)?;
    Ok(empty)
}

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().collect();
    let id = args
        .windows(2)
        .find(|a| a[0] == "--machine-id")
        .map(|a| a[1].as_str())
        .ok_or("--machine-id is required")?;
    let root = args
        .windows(2)
        .find(|a| a[0] == "--workspace")
        .map(|a| a[1].clone());
    let workspace = if let Some(root) = root {
        Workspace::open(root.into())?
    } else {
        Workspace::discover()?
    };
    let machine = workspace.machine_dir(id)?;
    let config = read_json(&machine.join("runtime/config.json"))?;
    let default_core = if config
        .get("sound_compatibility")
        .and_then(Value::as_bool)
        .unwrap_or(true)
    {
        "melondsds_system_compat.dll"
    } else {
        "melondsds_libretro.dll"
    };
    let core_name = args
        .windows(2)
        .find(|a| a[0] == "--core-file")
        .map(|a| a[1].as_str())
        .unwrap_or(default_core);
    if !core_name.ends_with(".dll")
        || core_name.contains("..")
        || !core_name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.')
    {
        return Err("Invalid libretro core filename".into());
    }
    let core_path = workspace.root.join("imports/libretro").join(core_name);
    let core_meta = std::fs::symlink_metadata(&core_path).map_err(|e| e.to_string())?;
    if !core_meta.is_file() || core_meta.file_type().is_symlink() {
        return Err("Libretro core must be a regular file in imports/libretro".into());
    }
    stage("Checking boot sources");
    stage("Preparing firmware and NAND working copies");
    let session = Session::prepare(&workspace, id)?;
    stage("Working copies ready");
    let mut slot = read_json(&machine.join("runtime/cartridge.json")).unwrap_or(Value::Null);
    let cartridge = if slot.get("inserted").and_then(Value::as_bool) == Some(true) {
        let rel = slot
            .get("image")
            .and_then(Value::as_str)
            .ok_or("Cartridge path missing")?;
        let path = machine.join(rel);
        if !path.starts_with(&machine)
            || hash_file(&path)? != slot["metadata"]["sha256"].as_str().unwrap_or("")
        {
            return Err("Cartridge hash changed".into());
        }
        Some(path)
    } else {
        None
    };
    stage("Starting melonDS core");
    let core = match Core::open(
        &core_path,
        &session.system,
        &session.save,
        session.sd_enabled,
        cartridge.as_deref(),
    ) {
        Ok(core) => core,
        Err(error) => {
            let _ = session.finish(0);
            return Err(error);
        }
    };
    session.running()?;
    send(json!({"kind":"ready","sample_rate":core.sample_rate,"backend":"melonDS DS libretro",
        "core":core_name,"live_cartridge":core.live_cart_supported()}));
    send(json!({"kind":"cartridge","inserted":core.cart_inserted().unwrap_or(cartridge.is_some()),
        "title":slot.pointer("/metadata/banner_title_english").or_else(||slot.pointer("/metadata/title_from_header")),
        "live_supported":core.live_cart_supported()}));
    let (tx, rx) = mpsc::channel::<Value>();
    std::thread::spawn(move || {
        for line in io::stdin().lock().lines() {
            let Ok(line) = line else { break };
            if let Ok(value) = serde_json::from_str::<Value>(&line) {
                if tx.send(value).is_err() {
                    return;
                }
            }
        }
        let _ = tx.send(json!({"kind":"stop"}));
    });
    let mut paused = false;
    let mut frames = 0u64;
    let mut next = Instant::now();
    let mut pending_audio = Vec::new();
    let mut buttons = std::collections::HashMap::<String, bool>::new();
    let mut last_touch = (0i64, 0i64, false);
    'running: loop {
        while let Ok(command) = rx.try_recv() {
            match command.get("kind").and_then(Value::as_str).unwrap_or("") {
                "stop" => break 'running,
                "pause" => {
                    paused = !paused;
                    pending_audio.clear();
                    session.status(true, paused, frames)?;
                    send(json!({"kind":"status","running":true,"paused":paused,"frames":frames}));
                }
                "reset" => {
                    core.reset();
                    session.status(true, paused, frames)?;
                    send(json!({"kind":"status","running":true,"paused":paused,"frames":frames}));
                }
                "cartridge_insert" => {
                    let result = command.get("path").and_then(Value::as_str)
                        .ok_or("Cartridge path missing".to_owned())
                        .and_then(|path| live_insert(&core, &machine, Path::new(path)));
                    match result {
                        Ok(record) => {
                            slot = record;
                            record_cartridge_event(&machine, "CARTRIDGE_INSERTED", &slot);
                            send(json!({"kind":"cartridge","inserted":true,
                                "title":slot.pointer("/metadata/banner_title_english").or_else(||slot.pointer("/metadata/title_from_header")),
                                "live_supported":true}));
                        }
                        Err(message) => send(json!({"kind":"cartridge_error","message":message})),
                    }
                }
                "cartridge_eject" => match live_eject(&core, &machine, &slot) {
                    Ok(empty) => {
                        record_cartridge_event(&machine, "CARTRIDGE_EJECTED", &slot);
                        slot = empty;
                        send(json!({"kind":"cartridge","inserted":false,"title":null,"live_supported":true}));
                    }
                    Err(message) => send(json!({"kind":"cartridge_error","message":message})),
                },
                "input" => {
                    if let (Some(name), Some(pressed)) =
                        (command["button"].as_str(), command["pressed"].as_bool())
                    {
                        Core::button(name, pressed);
                        if buttons.insert(name.to_owned(), pressed) != Some(pressed) {
                            session.diagnostic(json!({"timestamp":time::OffsetDateTime::now_utc().format(&time::format_description::well_known::Rfc3339).unwrap_or_default(),"kind":"INPUT","source":"CPF window","button":name,"pressed":pressed}));
                        }
                    }
                }
                "touch" => {
                    if let (Some(x), Some(y), Some(pressed)) = (
                        command["x"].as_i64(),
                        command["y"].as_i64(),
                        command["pressed"].as_bool(),
                    ) {
                        Core::touch(x, y, pressed);
                        let current = (x, y, pressed);
                        if current != last_touch && (pressed || last_touch.2) {
                            session.diagnostic(json!({"timestamp":time::OffsetDateTime::now_utc().format(&time::format_description::well_known::Rfc3339).unwrap_or_default(),"kind":"TOUCH","source":"CPF window","x":if pressed{Some(x)}else{None},"y":if pressed{Some(y)}else{None},"active":pressed}));
                        }
                        last_touch = current;
                    }
                }
                _ => {}
            }
        }
        if !paused {
            core.run();
            frames += 1;
            let (frame, audio) = Core::take_output();
            pending_audio.extend(audio);
            if frames % 2 == 0 {
                if let Some(frame) = frame {
                    send(
                        json!({"kind":"frame","width":frame.width,"height":frame.height,"pitch":frame.pitch,"frames":frames,"bgra":STANDARD.encode(frame.bytes),"audio":STANDARD.encode(&pending_audio)}),
                    );
                    pending_audio.clear();
                }
            }
            if frames % 60 == 0 {
                session.status(true, false, frames)?;
            }
        }
        next += Duration::from_nanos(16_666_667);
        let now = Instant::now();
        if next > now {
            std::thread::sleep(next - now);
        } else if now.duration_since(next) > Duration::from_millis(100) {
            next = now;
        }
    }
    if core.live_cart_supported() && core.cart_inserted() == Some(true) {
        save_current_cartridge(&core, &machine, &slot)?;
    }
    drop(core);
    session.finish(frames)?;
    Ok(())
}
fn main() {
    if let Err(error) = run() {
        eprintln!("CPF runtime error: {error}");
        send(json!({"kind":"error","message":error}));
    }
    send(json!({"kind":"stopped"}));
}
